// Builds the emails our apps send (emails/*.mjml + .txt + .json) into dist/.
//
//   dist/<brand>/<name>.html|.txt|.json   compiled templates, {{placeholders}} intact
//   dist/preview/<name>--<sample>.html|.txt  filled with each sample, for looking at
//   dist/node/email-templates.ts          all templates as one TypeScript module for the
//                                         Afiax Clinical Suite server
//
// See CONTENT.md for how to write the emails and which Mustache forms are allowed.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename } from 'node:path';
import mjml2html from 'mjml';
import Mustache from 'mustache';
import { stripDeadIE } from './build.mjs';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const emailsDir = join(repoRoot, 'emails');
const distDir = join(repoRoot, 'dist');

// The server renders with a small Mustache subset (variables, sections, inverted sections,
// comments). Fail the build if a template uses anything else, so it can't break at send time.
const ALLOWED_TOKENS = new Set(['text', 'name', '#', '^', '!']);

function checkTemplate(template, label) {
  const walk = (tokens) => {
    for (const t of tokens) {
      if (!ALLOWED_TOKENS.has(t[0])) {
        throw new Error(`${label}: Mustache tag "${t[0]}${t[1]}" is not allowed (see CONTENT.md).`);
      }
      if (t[4]) walk(t[4]);
    }
  };
  walk(Mustache.parse(template));
}

const noEscape = { escape: (s) => String(s) };

async function buildEmail(file) {
  const name = basename(file, '.mjml');
  const meta = JSON.parse(readFileSync(join(emailsDir, `${name}.json`), 'utf8'));
  const brand = meta.brand;

  const mjmlPath = join(emailsDir, file);
  const { html: rawHtml, errors } = await mjml2html(readFileSync(mjmlPath, 'utf8'), {
    filePath: mjmlPath,
    validationLevel: 'strict',
    ignoreIncludes: false, // MJML 5 skips mj-include silently unless this is set
    keepComments: false,
  });
  if (errors?.length) {
    throw new Error(`${file}:\n${errors.map((e) => `  ${e.formattedMessage ?? e.message}`).join('\n')}`);
  }
  const html = stripDeadIE(rawHtml, file);

  const footer = readFileSync(join(emailsDir, 'partials', `${brand}-footer.txt`), 'utf8');
  const text = readFileSync(join(emailsDir, `${name}.txt`), 'utf8').replace('{{> footer}}', footer.trimEnd());

  checkTemplate(html, `${name}.html`);
  checkTemplate(text, `${name}.txt`);
  checkTemplate(meta.subject, `${name}.json subject`);

  mkdirSync(join(distDir, brand), { recursive: true });
  writeFileSync(join(distDir, brand, `${name}.html`), html);
  writeFileSync(join(distDir, brand, `${name}.txt`), text);
  writeFileSync(join(distDir, brand, `${name}.json`), JSON.stringify({ subject: meta.subject, fields: meta.fields }, null, 2) + '\n');

  mkdirSync(join(distDir, 'preview'), { recursive: true });
  const previews = [];
  for (const [sample, data] of Object.entries(meta.samples ?? {})) {
    const subject = Mustache.render(meta.subject, data, {}, noEscape);
    const filled = Mustache.render(html, data).replace(/<title>.*?<\/title>/s, `<title>${Mustache.escape(subject)}</title>`);
    const filledText = Mustache.render(text, data, {}, noEscape).replace(/\n{3,}/g, '\n\n');
    writeFileSync(join(distDir, 'preview', `${name}--${sample}.html`), filled);
    writeFileSync(join(distDir, 'preview', `${name}--${sample}.txt`), `Subject: ${subject}\n\n${filledText}`);
    previews.push({ file: `${name}--${sample}.html`, subject });
  }

  console.log(`  ${file} -> dist/${brand}/${name}.html (+ ${previews.length} preview${previews.length === 1 ? '' : 's'})`);
  return { name, subject: meta.subject, html, text, previews };
}

function writeNodeModule(built) {
  const entries = built
    .map(
      (b) =>
        `  ${JSON.stringify(b.name)}: {\n` +
        `    subject: ${JSON.stringify(b.subject)},\n` +
        `    html: ${JSON.stringify(b.html)},\n` +
        `    text: ${JSON.stringify(b.text)},\n` +
        `  },`
    )
    .join('\n');
  const source = `// Generated by oortcloud-email-templates (npm run build:emails). Do not edit by hand:
// change the template in that repository, rebuild, and copy this file over.
/* eslint-disable */
// prettier-ignore
export const emailTemplates = {
${entries}
} as const;

export type EmailTemplateName = keyof typeof emailTemplates;
`;
  mkdirSync(join(distDir, 'node'), { recursive: true });
  writeFileSync(join(distDir, 'node', 'email-templates.ts'), source);
}

function writePreviewIndex(built) {
  const items = built
    .flatMap((b) => b.previews)
    .map((p) => `<li><a href="${p.file}">${Mustache.escape(p.subject)}</a> · <a href="${p.file.replace(/\.html$/, '.txt')}">text</a></li>`)
    .join('\n');
  writeFileSync(
    join(distDir, 'preview', 'index.html'),
    `<!doctype html><meta charset="utf-8"><title>Email previews</title><body style="font-family:sans-serif;max-width:720px;margin:40px auto;padding:0 16px"><h1>Email previews</h1><ul>${items}</ul></body>`
  );
}

export async function buildEmails() {
  rmSync(distDir, { recursive: true, force: true });
  const files = readdirSync(emailsDir).filter((f) => f.endsWith('.mjml')).sort();
  console.log(`Building ${files.length} email${files.length === 1 ? '' : 's'}...`);
  const built = [];
  for (const file of files) built.push(await buildEmail(file));
  writeNodeModule(built);
  writePreviewIndex(built);
  console.log('Done. Previews: dist/preview/index.html');
}

if (fileURLToPath(import.meta.url) === process.argv[1]) {
  await buildEmails();
}
